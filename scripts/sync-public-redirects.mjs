/**
 * Writes public/_redirects from the single-hop PATH_REDIRECTS map + checkout 302s.
 * Run before deploy / as part of build so Cloudflare never sees stale multi-hop rules.
 */
import fs from 'node:fs';
import path from 'node:path';
import { PATH_REDIRECTS, auditRedirectGraph } from './redirects.mjs';
import { LEGACY_LOCALE_CODES } from '../src/data/forum-consolidations.mjs';
import { CHECKOUT_PATH_REDIRECTS } from '../src/config/checkout-redirects.mjs';
import { TEMPLATE_CANONICAL_DOMAIN, TEMPLATE_SITE_URL } from './template-site.mjs';

const root = process.cwd();
const outFile = path.join(root, 'public', '_redirects');

const issues = auditRedirectGraph();
const loops = issues.filter((i) => i.type === 'loop');
const chains = issues.filter((i) => i.type === 'chain');
if (loops.length) {
  console.error('Redirect loops detected:', loops);
  process.exit(1);
}
if (chains.length) {
  console.error('Multi-hop redirect chains (must be single-hop):', chains);
  process.exit(1);
}

const lines = [
  '# Generated by scripts/sync-public-redirects.mjs — do not hand-edit.',
  '# Checkout (same-tab 302 → owner-supplied URL)',
];

// Preserve links to the former PNG/JPEG files for every available WebP master.
// Legacy raster paths may redirect to WebP masters when present under public/images/.
for (const folder of ['brand', 'gallery']) {
  const dir = path.join(root, 'public', 'images', folder);
  if (!fs.existsSync(dir)) continue;
  for (const name of fs.readdirSync(dir)) {
    if (!name.endsWith('.webp') || /-\d+\.webp$/.test(name)) continue;
    const stem = name.slice(0, -5);
    const target = encodeURI(`/images/${folder}/${name}`);
    for (const ext of ['png', 'jpg', 'jpeg']) {
      lines.push(`${encodeURI(`/images/${folder}/${stem}.${ext}`)}  ${target}  301`);
    }
  }
}

for (const [from, url] of CHECKOUT_PATH_REDIRECTS) {
  lines.push(`${from}  ${url}  302`);
}

lines.push('', '# Static path redirects (301, single-hop finals only)');

/** Prefer unique from→to pairs; include both slash variants already in the Map. */
const seen = new Set();
const sorted = [...PATH_REDIRECTS.entries()].sort((a, b) => a[0].localeCompare(b[0]));
for (const [from, to] of sorted) {
  const key = `${from}→${to}`;
  if (seen.has(key)) continue;
  seen.add(key);
  lines.push(`${from}  ${to}  301`);
}

lines.push('', '# Legacy locale prefixes → English (strip /{lang}/)');
for (const code of LEGACY_LOCALE_CODES) {
  lines.push(`/${code}  /  301`);
  lines.push(`/${code}/  /  301`);
  lines.push(`/${code}/*  /:splat  301`);
}

lines.push('', '# Canonical 404 URL (trailing slash) serves the static 404 document');
lines.push('/404/  /404.html  200');
lines.push('', '# Crawler files must stay extension URLs (Google fetches /robots.txt exactly)');
for (const file of [
  'robots.txt',
  'llms.txt',
  'sitemap.xml',
  'sitemap-index.xml',
  'sitemap-pages.xml',
  'sitemap-products.xml',
  'sitemap-blog.xml',
  'sitemap-forum.xml',
  'sitemap-all.xml',
  'sitemap-0.xml',
]) {
  lines.push(`/${file}/  /${file}  301`);
}
lines.push('', '# Production host only — www/http variants are not indexable');
const apex = TEMPLATE_SITE_URL;
const www = `https://www.${TEMPLATE_CANONICAL_DOMAIN}`;
lines.push(`${www}/*  ${apex}/:splat  301`);
lines.push(`http://www.${TEMPLATE_CANONICAL_DOMAIN}/*  ${apex}/:splat  301`);
lines.push(`http://${TEMPLATE_CANONICAL_DOMAIN}/*  ${apex}/:splat  301`);
lines.push('');
fs.writeFileSync(outFile, lines.join('\n'), 'utf8');
console.log(`Wrote ${seen.size} redirect rules → ${path.relative(root, outFile)}`);
